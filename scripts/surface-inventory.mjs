import fs from 'node:fs';
import postcss from 'postcss';

// Source guard for visual chrome. SVG coordinates/strokes belong to the artwork,
// not CSS layout units. Zero/none/inherit are explicit resets, not new design values.
const files = ['src/app/globals.css'];
const rows = [], errors = [];
for (const file of files) {
  postcss.parse(fs.readFileSync(file, 'utf8')).walkDecls(decl => {
    if (!/^(border(?:-.+)?|box-shadow|outline(?:-.+)?|aspect-ratio|object-fit|object-position)$/.test(decl.prop)) return;
    const selector = decl.parent.selector;
    rows.push([file, selector, decl.prop, decl.value]);
    if (/^(border(?:-.+)?|box-shadow|outline(?:-.+)?)$/.test(decl.prop)) {
      const literal = decl.value.replace(/var\([^)]*\)/g, '');
      if (/(?:\d*\.)?\d+(?:px|rem|em|%)/.test(literal.replace(/\b0(?:px|rem|em)?\b/g, ''))) errors.push(`${file}: ${selector}: ${decl.toString()}`);
    }
  });
}
fs.writeFileSync('docs/surface-usage.md', '# Surface usage\n\nGenerated by `node scripts/surface-inventory.mjs`. Decisions: [icon-surface-audit.md](icon-surface-audit.md). Artwork viewboxes and mesh stroke values are not CSS layout exceptions. Photo-specific ratios and positions remain documented composition choices.\n\n| File | Selector | Property | Token / value |\n| --- | --- | --- | --- |\n' + rows.map(row => '| ' + row.map(v => '`'+v+'`').join(' | ') + ' |').join('\n') + '\n');
if (errors.length) { console.error(errors.join('\n')); process.exitCode = 1; }
else console.log(`Validated ${rows.length} surface declarations in ${files.length} stylesheets.`);
