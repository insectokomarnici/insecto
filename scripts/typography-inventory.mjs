import fs from 'node:fs';
import path from 'node:path';
import postcss from 'postcss';

// Source audit: typography values belong to tokens.css; intentional inherit,
// normal tracking and zero line-height for image-only logo links are allowed.
const files = ['src/app/globals.css', 'src/app/o-namav1/page.module.css'];
const properties = /^(font-family|font-size|font-weight|line-height|letter-spacing|font-variant-numeric|text-transform)$/;
const rows = [];
const errors = [];
for (const file of files) {
  postcss.parse(fs.readFileSync(file, 'utf8'), { from: file }).walkDecls(decl => {
    if (!properties.test(decl.prop)) return;
    const selector = decl.parent.selector;
    rows.push([file, selector, decl.prop, decl.value]);
    if (!(selector === 'html' && decl.prop === 'font-size' && decl.value === '100%') && /^(font-family|font-size|font-weight|line-height|letter-spacing)$/.test(decl.prop) && !/^(var\(--[\w-]+\)|inherit|normal|0)$/.test(decl.value)) errors.push(`${file}: ${selector}: ${decl.toString()}`);
  });
}
const header = '# Typography usage\n\nGenerated by `node scripts/typography-inventory.mjs`. Token definitions: `src/app/tokens.css`. Decisions: [typography-audit.md](typography-audit.md). Inherited body text uses Manrope 400, 1rem / 1.625. Inline weights are allowed only in the explicit weight comparison demo.\n\n| File | Selector | Property | Token / value |\n| --- | --- | --- | --- |\n';
fs.writeFileSync(path.join('docs', 'typography-usage.md'), header + rows.map(row => '| ' + row.map(v => '`' + v + '`').join(' | ') + ' |').join('\n') + '\n');
if (errors.length) { console.error(errors.join('\n')); process.exitCode = 1; }
else console.log(`Validated ${rows.length} typography declarations in ${files.length} stylesheets.`);
