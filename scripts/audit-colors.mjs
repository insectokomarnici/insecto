import fs from 'node:fs';
import postcss from 'postcss';

// WCAG 2.x sRGB relative luminance. Alpha is composited before comparison;
// never round ratios before testing the threshold. This tests approved token
// pairings, not arbitrary image content or the entire accessibility standard.
const tokenSource = fs.readFileSync('src/app/tokens.css', 'utf8');
const tokens = new Map();
postcss.parse(tokenSource).walkDecls(decl => {
  if (decl.prop.startsWith('--color-') && decl.parent.type === 'atrule' && decl.parent.name === 'theme') tokens.set(decl.prop.slice(8), decl.value.replace(/\/\*.*?\*\//g, '').trim());
});
function rgb(value) {
  if (/^#[\da-f]{6}$/i.test(value)) return value.slice(1).match(/../g).map(v => Number.parseInt(v, 16)).concat(1);
  const match = value.match(/^rgb\((\d+) (\d+) (\d+) \/ ([.\d]+)\)$/);
  if (match) return match.slice(1).map(Number);
  throw new Error(`Unsupported color: ${value}`);
}
const color = name => rgb(tokens.get(name));
const over = (fg, bg) => fg.slice(0, 3).map((v, i) => v * fg[3] + bg[i] * (1 - fg[3])).concat(1);
const luminance = value => value.slice(0, 3).map(v => { v /= 255; return v <= 0.04045 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4; }).reduce((sum, v, i) => sum + v * [0.2126, 0.7152, 0.0722][i], 0);
const contrast = (a, b) => (Math.max(luminance(a), luminance(b)) + 0.05) / (Math.min(luminance(a), luminance(b)) + 0.05);
const pairs = [];
function check(role, foreground, background, threshold, canvas = 'surface') {
  const bg = typeof background === 'string' ? over(color(background), color(canvas)) : background;
  const fg = over(color(foreground), bg);
  const ratio = contrast(fg, bg);
  pairs.push({role, foreground, background: typeof background === 'string' ? background : 'composited worst case', threshold, ratio, pass: ratio >= threshold});
}
for (const bg of ['surface', 'surface-subtle']) {
  for (const fg of ['heading', 'body', 'brand', 'placeholder']) check(`${fg} text on ${bg}`, fg, bg, 4.5);
  check(`Input boundary on ${bg}`, 'control-border', bg, 3);
  check(`Keyboard / pointer focus on ${bg}`, 'brand-light', bg, 3);
  check(`Rating contour on ${bg}`, 'rating-outline', bg, 3);
}
for (const bg of ['brand', 'brand-light']) check(`White text on ${bg}`, 'surface', bg, 4.5);
check('Success notice', 'success', 'success-surface', 4.5);
check('Error notice', 'error', 'error-surface', 4.5);
check('Error boundary inside white input', 'error', 'surface', 3);
check('Inverse error boundary', 'error-on-brand', 'brand', 3);
check('Focus on brand panel / announcement', 'surface', 'brand', 3);
check('Upload hint on brand', 'upload-muted', 'brand', 4.5);
const upload = over(color('upload-surface'), color('brand'));
check('Upload action', 'surface', upload, 4.5);
check('Upload icon', 'upload-muted', upload, 3);
check('Upload boundary', 'upload-border', upload, 3);
check('Upload error boundary', 'error-on-brand', upload, 3);
const caption = over(color('gallery-caption-surface'), color('surface'));
check('Gallery title over white photo', 'surface', caption, 4.5);
check('Gallery category over white photo', 'gallery-caption-muted', caption, 4.5);
check('Google verification graphic', 'google-blue', 'surface', 3);
check('Accent badge text / selection', 'brand', 'accent-surface', 4.5);
// The CTA explicitly interpolates in sRGB. Sample the entire gradient, not
// only its endpoints, so future palette changes cannot silently break it.
const start = color('brand-light'), end = color('brand');
const gradientRatios = Array.from({length: 101}, (_, i) => contrast(color('surface'), start.map((v, k) => v + (end[k] - v) * i / 100)));
pairs.push({role:'White CTA text across sRGB gradient',foreground:'surface',background:'primary-gradient (101 samples)',threshold:4.5,ratio:Math.min(...gradientRatios),pass:Math.min(...gradientRatios)>=4.5});

const rows = [], literalErrors = [];
const stylesheets = fs.readdirSync('src', { recursive: true }).filter(file => file.endsWith('.css') && file !== 'app/tokens.css').map(file => `src/${file}`);
for (const file of stylesheets) {
  postcss.parse(fs.readFileSync(file, 'utf8')).walkDecls(decl => {
    if (!/(color|background|border|outline|shadow|fill|stroke)/.test(decl.prop)) return;
    if (/var\(--(?:color-|primary-gradient|accent-gradient|focus-ring|shadow-)/.test(decl.value)) rows.push([file,decl.parent.selector,decl.prop,decl.value]);
    if (/#(?:[\da-f]{3})\b|#[\da-f]{6,8}\b|\b(?:rgb|hsl)a?\(/i.test(decl.value)) literalErrors.push(`${file}: ${decl.toString()}`);
  });
}
fs.writeFileSync('docs/color-usage.md', '# Color usage\n\nGenerated by `node scripts/audit-colors.mjs`. Decisions and exclusions: [color-contrast-audit.md](color-contrast-audit.md). Canonical values: `src/app/tokens.css`. Google logo path fills are intentional external-brand artwork, not UI color overrides.\n\n| File | Selector | Property | Value |\n| --- | --- | --- | --- |\n'+rows.map(row=>'| '+row.map(v=>'`'+v+'`').join(' | ')+' |').join('\n')+'\n');
fs.writeFileSync('docs/contrast-ratios.md', '# Verified contrast pairs\n\nGenerated from current tokens by `node scripts/audit-colors.mjs`. Ratios are rounded only for display; passing uses the unrounded value. 4.5:1 is used conservatively for all text pairs, 3:1 for meaningful boundaries/graphics. Decorative card borders, disabled controls and original brand artwork are not required to pass these thresholds. Hover/selected/active roles reuse these pairs; browser state verification is recorded in [color-contrast-audit.md](color-contrast-audit.md).\n\n| Role | Foreground | Background | Ratio | Required | Result |\n| --- | --- | --- | --- | --- | --- |\n'+pairs.map(p=>`| ${p.role} | ${p.foreground} | ${p.background} | ${p.ratio.toFixed(2)}:1 | ${p.threshold}:1 | ${p.pass?'Pass':'FAIL'} |`).join('\n')+'\n');
const failures = pairs.filter(p=>!p.pass);
if (literalErrors.length || failures.length) { console.error({literalErrors,failures});process.exitCode=1; }
else console.log(`${pairs.length} contrast pairs pass; ${rows.length} CSS color consumers inventoried.`);
