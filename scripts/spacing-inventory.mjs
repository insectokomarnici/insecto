/* Generate the exact selector/property inventory and reject unowned spacing.
 * Run after editing CSS: node scripts/spacing-inventory.mjs
 * Zero/auto and the native visually-hidden -1px margin are intentional exceptions.
 */
import fs from 'node:fs';
const files=['src/app/globals.css'];
const sources=['src/app/tokens.css',...files].map(f=>fs.readFileSync(f,'utf8'));
const definitions=new Set(sources.join('\n').match(/--[\w-]+(?=\s*:)/g));
const errors=[];
for(const source of sources)for(const match of source.matchAll(/var\((--[\w-]+)/g))if(!definitions.has(match[1]))errors.push(`Undefined token ${match[1]}`);
let out='# Spacing usage inventory\n\nGenerated by `node scripts/spacing-inventory.mjs`. Values live in `src/app/tokens.css`; this file lists consumers, including breakpoint overrides. Zero resets, auto alignment and the visually hidden radio offset are intentional. Illustrative dimensions on `/design-system` are not public layout spacing.\n';
for(const file of files){
 const css=fs.readFileSync(file,'utf8');
 out+=`\n## ${file}\n\n| Line | Selector | Spacing declarations |\n| --- | --- | --- |\n`;
 for(const match of css.matchAll(/([^{}]+)\{([^{}]*)\}/g)){
  const selector=match[1].replace(/\/\*[\s\S]*?\*\//g,'').trim();
  const props=match[2].split(';').map(s=>s.trim()).filter(s=>/^(?:(?:row-|column-)?gap|(?:scroll-)?(?:margin|padding)[\w-]*|inset[\w-]*|top|right|bottom|left)\s*:/.test(s));
  if(!props.length)continue;
  const line=css.slice(0,match.index+match[1].indexOf(selector.split('\n')[0])).split('\n').length;
  for(const prop of props){
   if(/var\(--space-/.test(prop))errors.push(`${file}:${line} base scale used directly: ${prop}`);
   const stripped=prop.replace(/var\([^)]*\)/g,'');
   if(/\b\d+(?:\.\d+)?(?:px|rem)\b/.test(stripped)&&!(selector==='.radio-choice-input'&&prop==='margin: -1px'))errors.push(`${file}:${line} unowned spacing: ${prop}`);
  }
  out+=`| ${line} | \`${selector.replace(/\s+/g,' ')}\` | ${props.map(p=>'`'+p+'`').join('<br>')} |\n`;
 }
}
if(errors.length){console.error(errors.join('\n'));process.exit(1)}
fs.writeFileSync('docs/spacing-usage.md',out);
console.log('All spacing declarations use semantic tokens; inventory updated.');
